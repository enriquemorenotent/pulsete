export function nordVpnCountryFlag(location: string): string | null {
  const country = nordVpnCountry(location);
  const proxy = nordVpnLocations.find(([id]) => id === location);
  const code = country
    ? countryCodes[country as keyof typeof countryCodes]
    : proxy?.[2].match(/\.([a-z]{2})\.socks\.nordhold\.net$/)?.[1].toUpperCase();
  if (!code || !/^[A-Z]{2}$/.test(code)) return null;
  return String.fromCodePoint(...Array.from(code, letter => 0x1F1E6 + letter.charCodeAt(0) - 65));
}
